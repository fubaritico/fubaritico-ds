import clsx from 'clsx'
import { useCallback, useEffect, useRef, useState } from 'react'

import {
  IMAGE_BLUR_CLASS,
  IMAGE_CLASS,
  IMAGE_FALLBACK_CLASS,
  imageVariants,
} from '@fubaritico/variants'

import { getBlurDataUrl } from '../../utils'
import { Icon } from '../Icon'

import type { ComponentProps, ReactNode } from 'react'

/** Pixel size of the placeholder glyph shown when the source fails. */
const FALLBACK_ICON_SIZE = 48

/** Loading lifecycle of the {@link Image}. */
export type ImageState = 'loading' | 'loaded' | 'error'

/** Preset aspect ratios of the frame; any CSS `aspect-ratio` string is accepted too. */
export type AspectRatio = '2/3' | '16/9' | '1/1' | '4/3' | '3/2'

/** When the real source is requested: on entering the viewport, or straight away. */
export type ImageLoading = 'lazy' | 'eager'

/** Props of the {@link Image}. */
export interface ImageProps
  extends Omit<ComponentProps<'img'>, 'placeholder' | 'onLoad' | 'onError'> {
  /** Image source URL. */
  src: string
  /** Alternative text — pass `""` for a purely decorative image. */
  alt: string
  /** Pre-generated blur placeholder (a data URL), shown while the source loads. */
  blurDataUrl?: string
  /** Generate the blur placeholder from `src` through a canvas; ignored when `blurDataUrl` is set. */
  autoBlur?: boolean
  /** Side of the blur canvas in pixels — smaller means blurrier; defaults to `16`. */
  blurSize?: number
  /** JPEG quality of the generated blur, `0`–`1`; defaults to `0.3`. */
  blurQuality?: number
  /** Aspect ratio of the frame; defaults to `'2/3'`. */
  aspectRatio?: AspectRatio | (string & {})
  /** Content shown instead of the picture when the source fails; defaults to a photo glyph. */
  fallback?: ReactNode
  /** Called once the source has loaded. */
  onLoad?: () => void
  /** Called when the source fails to load. */
  onError?: () => void
  /**
   * Load strategy: `'lazy'` waits until the frame is within 50px of the viewport, `'eager'`
   * requests at once. Defaults to `'eager'`.
   */
  loading?: ImageLoading
}

/**
 * Image — a ratio-locked media frame with a progressive reveal.
 *
 * The frame's height comes from the aspect ratio, never from the picture, so nothing reflows when
 * it arrives. While loading, an optional blur placeholder fills the frame; the picture fades in on
 * decode; a failed source is replaced by the fallback. `'lazy'` defers the request until the frame
 * nears the viewport.
 *
 * @param props - {@link ImageProps}.
 * @param props.src - Source URL.
 * @param props.alt - Alternative text.
 * @param props.blurDataUrl - Pre-generated blur placeholder.
 * @param props.autoBlur - Generate the placeholder from `src`.
 * @param props.blurSize - Side of the blur canvas; defaults to `16`.
 * @param props.blurQuality - JPEG quality of the blur; defaults to `0.3`.
 * @param props.aspectRatio - Frame ratio; defaults to `'2/3'`.
 * @param props.fallback - Content shown when the source fails.
 * @param props.onLoad - Called once the source has loaded.
 * @param props.onError - Called when the source fails.
 * @param props.loading - `'lazy'` or `'eager'`; defaults to `'eager'`.
 * @returns The rendered frame.
 */
export function Image({
  src,
  alt,
  blurDataUrl,
  autoBlur = false,
  blurSize = 16,
  blurQuality = 0.3,
  aspectRatio = '2/3',
  fallback,
  className,
  onLoad,
  onError,
  loading = 'eager',
  ...rest
}: Readonly<ImageProps>) {
  // The <img>, to detect a source already decoded from cache.
  const imgRef = useRef<HTMLImageElement>(null)
  // The frame, observed for the lazy strategy.
  const containerRef = useRef<HTMLDivElement>(null)
  // Loading lifecycle, mirrored on `data-state`.
  const [state, setState] = useState<ImageState>('loading')
  // Placeholder generated by `autoBlur`, when no `blurDataUrl` is given.
  const [generatedBlur, setGeneratedBlur] = useState<string | undefined>(
    undefined
  )
  // Holds the real request back until the generated placeholder is ready (or has failed).
  const [blurReady, setBlurReady] = useState(!autoBlur || !!blurDataUrl)
  // Whether the frame has neared the viewport — always true for `'eager'`.
  const [isVisible, setIsVisible] = useState(loading === 'eager')

  const effectiveBlur = blurDataUrl ?? generatedBlur

  // Lazy strategy: request the source once the frame comes within 50px of the viewport.
  useEffect(() => {
    if (loading === 'eager' || !containerRef.current) {
      return
    }

    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setIsVisible(true)
          observer.unobserve(entry.target)
        }
      },
      { rootMargin: '50px' }
    )

    observer.observe(containerRef.current)

    return () => {
      observer.disconnect()
    }
  }, [loading])

  // Generate the blur placeholder; a failure only drops the placeholder, never the picture.
  useEffect(() => {
    if (!autoBlur || blurDataUrl) {
      setBlurReady(true)
      return
    }

    setBlurReady(false)

    getBlurDataUrl(src, blurSize, blurQuality)
      .then((base64) => {
        setGeneratedBlur(base64)
        setBlurReady(true)
      })
      .catch((error: unknown) => {
        console.warn('[Image] blur placeholder generation failed', error)
        setBlurReady(true)
      })
  }, [autoBlur, src, blurDataUrl, blurSize, blurQuality])

  // A new source starts over — unless the browser already has it decoded from cache.
  useEffect(() => {
    setState('loading')
    setGeneratedBlur(undefined)

    // Check if image is already loaded from cache
    if (imgRef.current?.complete && imgRef.current.naturalHeight !== 0) {
      setState('loaded')
    }
  }, [src])

  // Stable handlers for the <img>: settle the state, then notify the consumer.
  const handleLoad = useCallback(() => {
    setState('loaded')
    onLoad?.()
  }, [onLoad])

  const handleError = useCallback(() => {
    setState('error')
    onError?.()
  }, [onError])

  // The picture is gone, but what it conveyed is not: the default fallback carries `alt` as its
  // own accessible name, so an informative image never fails into silence. A decorative one
  // (`alt=""`) stays out of the tree, as the picture itself would have.
  const defaultFallback = (
    <div
      className={IMAGE_FALLBACK_CLASS}
      {...(alt ? { role: 'img', 'aria-label': alt } : { 'aria-hidden': true })}
    >
      <Icon name="Photo" size={FALLBACK_ICON_SIZE} aria-hidden="true" />
    </div>
  )

  return (
    <div
      ref={containerRef}
      className={clsx(IMAGE_CLASS, className)}
      style={aspectRatio ? { aspectRatio } : undefined}
      data-state={state}
    >
      {state === 'error' ? (
        (fallback ?? defaultFallback)
      ) : (
        <>
          {effectiveBlur && state === 'loading' ? (
            <img
              src={effectiveBlur}
              alt=""
              aria-hidden="true"
              className={IMAGE_BLUR_CLASS}
            />
          ) : null}

          {blurReady && isVisible ? (
            <img
              ref={imgRef}
              src={src}
              alt={alt}
              onLoad={handleLoad}
              onError={handleError}
              className={imageVariants({ loaded: state === 'loaded' })}
              {...rest}
            />
          ) : null}
        </>
      )}
    </div>
  )
}

export default Image
